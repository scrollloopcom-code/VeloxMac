#!/usr/bin/env python3
"""
VeloxMac Native 1-Click YouTube Cookie Sync via Apple WebKit (WKWebView).
Opens a dedicated WebKit window to YouTube, allowing the user to sign in
or use their existing session, then extracts all cookies (including HttpOnly/Secure)
and exports them to standard Netscape cookies.txt format for yt-dlp.
"""

import sys
import os
import time
import json
import argparse
from datetime import datetime
from email.utils import parsedate_to_datetime
import webview

DEFAULT_COOKIE_PATH = os.path.expanduser("~/Downloads/VeloxDownloads/cookies.txt")

def format_netscape_cookie(morsel) -> str:
    """Converts an http.cookies Morsel object into a Netscape cookie line."""
    raw_domain = morsel['domain'] or '.youtube.com'
    httponly = bool(morsel.get('httponly', False))
    secure = 'TRUE' if morsel.get('secure', False) else 'FALSE'
    path = morsel.get('path') or '/'
    
    # Domain prefix for Netscape
    domain = raw_domain
    if httponly and not domain.startswith('#HttpOnly_'):
        domain = f"#HttpOnly_{raw_domain}"
    
    flag = 'TRUE' if raw_domain.startswith('.') else 'FALSE'
    
    # Expiration timestamp
    expires = morsel.get('expires')
    exp_ts = int(time.time() + 86400 * 365) # fallback 1 year
    if expires:
        try:
            exp_ts = int(parsedate_to_datetime(expires).timestamp())
        except Exception:
            try:
                exp_ts = int(datetime.strptime(str(expires)[:19], "%Y-%m-%d %H:%M:%S").timestamp())
            except Exception:
                pass
                
    name = morsel.key
    val = morsel.value
    return f"{domain}\t{flag}\t{path}\t{secure}\t{exp_ts}\t{name}\t{val}\n"

class CookieSyncApi:
    def __init__(self, output_path: str):
        self.output_path = output_path
        self.window = None
        self.captured = False
        self.count = 0

    def set_window(self, win):
        self.window = win

    def save_cookies(self) -> int:
        """Extracts and saves all cookies from WKWebView without closing."""
        if not self.window:
            return 0
        try:
            cookies = self.window.get_cookies()
            if not cookies:
                return 0
            lines = [
                "# Netscape HTTP Cookie File\n",
                "# Generated by VeloxMac 1-Click Cookie Sync\n",
                f"# Synced at: {datetime.now().isoformat()}\n"
            ]
            saved_count = 0
            for c in cookies:
                for _, morsel in c.items():
                    line = format_netscape_cookie(morsel)
                    lines.append(line)
                    saved_count += 1
            
            if saved_count > 0:
                os.makedirs(os.path.dirname(self.output_path), exist_ok=True)
                with open(self.output_path, "w", encoding="utf-8") as f:
                    f.writelines(lines)
                self.captured = True
                self.count = saved_count
            return saved_count
        except Exception:
            return 0

    def save_and_close(self):
        """Called by injected JS button or closing hook."""
        self.save_cookies()
        try:
            if self.window:
                self.window.destroy()
        except Exception:
            pass
        return {"status": "ok", "count": self.count}

