def background_auto_saver(window, api: CookieSyncApi):
    """Periodically captures and persists cookies to disk every 2 seconds."""
    time.sleep(2)
    while True:
        try:
            api.save_cookies()
        except Exception:
            break
        time.sleep(2)

def main():
    parser = argparse.ArgumentParser(description="VeloxMac 1-Click YouTube Cookie Sync")
    parser.add_argument("--output", default=DEFAULT_COOKIE_PATH, help="Path to save cookies.txt")
    parser.add_argument("--url", default="https://www.youtube.com", help="Initial URL")
    args = parser.parse_args()

    api = CookieSyncApi(args.output)
    win = webview.create_window(
        title="⚡ VeloxMac — 1-Click YouTube Login & Cookie Sync",
        url=args.url,
        width=880,
        height=680,
        js_api=api
    )
    api.set_window(win)

    # In case the user closes the window via macOS red X button
    def on_closing():
        api.save_and_close()

    win.events.closing += on_closing

    import threading
    # Thread 1: Injects floating banner
    t1 = threading.Thread(target=inject_sync_banner, args=(win,), daemon=True)
    t1.start()

    # Thread 2: Continuously auto-saves cookies every 2 seconds
    t2 = threading.Thread(target=background_auto_saver, args=(win, api), daemon=True)
    t2.start()

    webview.start()

    # Final save on exit just in case
    api.save_cookies()

    result = {
        "status": "ok",
        "captured": api.captured,
        "count": api.count,
        "path": args.output
    }
    print(json.dumps(result))

if __name__ == "__main__":
    main()
