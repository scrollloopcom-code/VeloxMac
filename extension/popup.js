// VeloxMac Cookie Bridge — Chrome/Brave Extension Popup Controller

let currentNetscapeCookies = "";
let totalCookieCount = 0;

document.addEventListener('DOMContentLoaded', async () => {
  await scanAndFormatCookies();
  setupEvents();
});

async function scanAndFormatCookies() {
  const countEl = document.getElementById('cookieCount');
  const sampleEl = document.getElementById('cookieSample');
  const syncBtn = document.getElementById('syncBtn');

  try {
    // Query all cookies for youtube.com and google.com
    const ytCookies = await chrome.cookies.getAll({ domain: "youtube.com" });
    const gCookies = await chrome.cookies.getAll({ domain: "google.com" });
    
    // Combine & deduplicate by domain + name + path
    const map = new Map();
    for (const c of [...ytCookies, ...gCookies]) {
      const key = `${c.domain}|${c.path}|${c.name}`;
      map.set(key, c);
    }

    const allCookies = Array.from(map.values());
    totalCookieCount = allCookies.length;

    if (totalCookieCount === 0) {
      countEl.innerText = "0 found";
      countEl.style.color = "var(--red)";
      sampleEl.innerText = "Please open and sign in to youtube.com in this browser first.";
      syncBtn.disabled = true;
      return;
    }

    // Build Netscape format
    const lines = [
      "# Netscape HTTP Cookie File",
      "# Generated by VeloxMac Chrome Bridge",
      `# Synced at: ${new Date().toISOString()}`
    ];

    const keyNames = [];
    for (const c of allCookies) {
      keyNames.push(c.name);

      let domain = c.domain;
      const isHttpOnly = Boolean(c.httpOnly);
      const isSubdomain = domain.startsWith(".");
      const flag = isSubdomain ? "TRUE" : "FALSE";
      const path = c.path || "/";
      const secure = c.secure ? "TRUE" : "FALSE";
      
      let exp = c.expirationDate ? Math.floor(c.expirationDate) : Math.floor(Date.now() / 1000) + (86400 * 365);
      
      if (isHttpOnly && !domain.startsWith("#HttpOnly_")) {
        domain = `#HttpOnly_${domain}`;
      }

      lines.push(`${domain}\t${flag}\t${path}\t${secure}\t${exp}\t${c.name}\t${c.value}`);
    }

    currentNetscapeCookies = lines.join("\n") + "\n";
    countEl.innerText = `${totalCookieCount} cookies found`;
    countEl.style.color = "var(--cyan)";

    // Highlight key auth tokens found
    const authFound = ["SID", "LOGIN_INFO", "HSID", "SSID", "SAPISID", "PREF"].filter(k => keyNames.includes(k));
    if (authFound.length > 0) {
      sampleEl.innerText = `Tokens: ${authFound.join(", ")} + ${totalCookieCount - authFound.length} more`;
    } else {
      sampleEl.innerText = keyNames.slice(0, 6).join(", ") + "...";
    }

    syncBtn.disabled = false;
  } catch (err) {
    countEl.innerText = "Error";
    countEl.style.color = "var(--red)";
    sampleEl.innerText = err.message;
    syncBtn.disabled = true;
  }
}

function setupEvents() {
  const syncBtn = document.getElementById('syncBtn');
  const copyBtn = document.getElementById('copyBtn');
  const statusBox = document.getElementById('statusBox');

  syncBtn.addEventListener('click', async () => {
    if (!currentNetscapeCookies) return;
    
    syncBtn.disabled = true;
    syncBtn.innerText = "⏳ Syncing to VeloxMac...";
    statusBox.className = "status-msg";
    statusBox.style.display = "none";

    try {
      const resp = await fetch("http://127.0.0.1:8899/api/cookies", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ cookie_text: currentNetscapeCookies })
      });

      if (resp.ok) {
        statusBox.className = "status-msg success";
        statusBox.innerText = `✅ Successfully synced ${totalCookieCount} cookies to VeloxMac! BotGuard Bypassed.`;
        syncBtn.innerText = "✅ Synced!";
      } else {
        const err = await resp.json();
        throw new Error(err.detail || "Server returned error");
      }
    } catch (err) {
      statusBox.className = "status-msg error";
      statusBox.innerText = `⚠️ Failed to reach VeloxMac (port 8899). Click 'Copy' and paste manually!`;
      syncBtn.innerText = "⚡ Retry Sync";
      syncBtn.disabled = false;
    }
  });

  copyBtn.addEventListener('click', async () => {
    if (!currentNetscapeCookies) return;
    try {
      await navigator.clipboard.writeText(currentNetscapeCookies);
      statusBox.className = "status-msg success";
      statusBox.innerText = `📋 Copied ${totalCookieCount} cookies to clipboard in Netscape format!`;
      copyBtn.innerText = "✅ Copied to Clipboard!";
      setTimeout(() => { copyBtn.innerText = "📋 Copy Netscape cookies.txt"; }, 2500);
    } catch (err) {
      statusBox.className = "status-msg error";
      statusBox.innerText = "Clipboard permission denied.";
    }
  });
}
