@app.post("/api/cookies/capture")
async def launch_cookie_capture():
    global active_capture_proc
    if active_capture_proc is not None and active_capture_proc.returncode is None:
        return {"status": "already_running", "message": "Capture window is already open."}

    cookie_script = os.path.join(BASE_DIR, "engine", "cookie_capture.py")
    python_bin = os.path.join(BASE_DIR, ".venv", "bin", "python3")
    cookie_path = os.path.join(DOWNLOADS_DIR, "cookies.txt")

    try:
        proc = await asyncio.create_subprocess_exec(
            python_bin, cookie_script, "--output", cookie_path,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE
        )
        active_capture_proc = proc

        async def monitor_capture():
            global active_capture_proc
            stdout, stderr = await proc.communicate()
            active_capture_proc = None
            try:
                out_text = stdout.decode().strip()
                res = json.loads(out_text.splitlines()[-1])
                count = res.get("count", 0)
            except Exception:
                count = 0
            
            job_manager.broadcast_update({
                "type": "cookies_updated",
                "count": count,
                "path": cookie_path
            })

        asyncio.create_task(monitor_capture())
        return {"status": "ok", "message": "Native WebKit YouTube window opened."}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to launch cookie capture: {str(e)}")

