@app.post("/api/inspect")
async def inspect_url(req: InspectRequest):
    url = req.url.strip()
    if not url:
        raise HTTPException(status_code=400, detail="URL cannot be empty")

    # Fast direct file extension check (.dmg, .pkg, .zip, .tar, .iso, etc.)
    direct_extensions = (".dmg", ".pkg", ".zip", ".tar.gz", ".tgz", ".iso", ".exe", ".bin", ".7z", ".rar", ".deb")
    is_likely_direct = any(url.lower().split("?")[0].endswith(ext) for ext in direct_extensions)

    if is_likely_direct:
        try:
            info = await SegmentedDownloader.inspect_url(url)
            return {
                "type": "direct",
                "info": info
            }
        except Exception:
            pass

    # Try media extraction first (yt-dlp handles 1000+ sites)
    try:
        loop = asyncio.get_running_loop()
        media_info = await loop.run_in_executor(
            None,
            lambda: media_extractor.inspect(url, browser_cookies=req.browser_cookies)
        )
        return {
            "type": "media",
            "info": media_info
        }
    except Exception as media_err:
        # Fallback to direct download inspection
        try:
            direct_info = await SegmentedDownloader.inspect_url(url)
            return {
                "type": "direct",
                "info": direct_info
            }
        except Exception as direct_err:
            raise HTTPException(
                status_code=400,
                detail=f"Unable to analyze URL as media or direct file: {str(media_err)}"
            )

