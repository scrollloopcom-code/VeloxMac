@app.post("/api/cookies")
def save_cookies(req: CookieRequest):
    text = req.cookie_text.strip()
    if not text:
        raise HTTPException(status_code=400, detail="Cookie content cannot be empty")
    
    # If raw cookie (e.g. "key=val; key2=val2") without Netscape header, format it
    if not text.startswith("# Netscape") and "\t" not in text:
        lines = ["# Netscape HTTP Cookie File\n", "# Generated by LoopCatch Cookie Manager\n"]
        for item in text.split(";"):
            item = item.strip()
            if not item or "=" not in item:
                continue
            k, v = item.split("=", 1)
            lines.append(f".youtube.com\tTRUE\t/\tTRUE\t2147483647\t{k.strip()}\t{v.strip()}\n")
        content = "".join(lines)
    else:
        content = text

    cookie_path = os.path.join(DOWNLOADS_DIR, "cookies.txt")
    with open(cookie_path, "w", encoding="utf-8") as f:
        f.write(content)
    
    # Save into Multi-Device Cookie Vault under the current PC's profile
    vault_res = cookie_vault.save_device_cookies(content, custom_device_name=req.device_name)
    valid_count = vault_res.get("cookie_count", 0)

    # Count valid cookie lines and broadcast real-time update to all open Web UI tabs!
    job_manager.broadcast_update({
        "type": "cookies_updated",
        "count": valid_count,
        "path": cookie_path,
        "device_id": vault_res.get("device_id"),
        "platforms": vault_res.get("platforms", [])
    })
    
    return {
        "status": "ok", 
        "message": f"Saved {valid_count} cookies to {vault_res.get('device_name')} vault!", 
        "count": valid_count,
        "vault": vault_res
    }

