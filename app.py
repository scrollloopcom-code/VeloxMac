@app.websocket("/ws")
async def websocket_endpoint(websocket: WebSocket):
    await websocket.accept()
    queue = job_manager.subscribe()
    try:
        # Send initial snapshot
        init_payload = {
            "type": "init",
            "jobs": [j.to_dict() for j in job_manager.jobs.values()]
        }
        await websocket.send_json(init_payload)

        # Loop to stream live job telemetry
        while True:
            # Poll queue or tick every 500ms
            try:
                msg = await asyncio.wait_for(queue.get(), timeout=0.5)
                await websocket.send_json(msg)
            except asyncio.TimeoutError:
                # Heartbeat with active jobs
                active = [j.to_dict() for j in job_manager.jobs.values() if j.status in ("downloading", "assembling")]
                if active:
                    await websocket.send_json({"type": "active_batch", "jobs": active})
    except (WebSocketDisconnect, Exception):
        pass
    finally:
        job_manager.unsubscribe(queue)

